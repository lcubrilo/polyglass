"""Write THIRD_PARTY_NOTICES.md: every library Polyglass ships with (runtime dependencies, recursively),
with its version, licence and homepage. Run after changing dependencies:

    python tools/third_party_notices.py
"""

import re
from importlib.metadata import PackageNotFoundError, distribution
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def requirement_name(req: str) -> str | None:
    if "extra ==" in req:  # optional extras are not shipped
        return None
    return re.split(r"[\s<>=!~;\[(]", req, maxsplit=1)[0]


def license_of(meta) -> str:
    expression = meta.get("License-Expression")
    if expression:
        return expression
    classifiers = [c.split("::")[-1].strip() for c in meta.get_all("Classifier") or [] if c.startswith("License ::")]
    if classifiers:
        return ", ".join(classifiers)
    text = (meta.get("License") or "").strip().splitlines()
    return text[0][:80] if text else "see project"


def homepage(meta) -> str:
    for entry in meta.get_all("Project-URL") or []:
        label, _, url = entry.partition(",")
        if label.strip().lower() in {"homepage", "home", "source", "repository", "source code"}:
            return url.strip()
    return meta.get("Home-page") or ""


def collect(root: str) -> dict[str, object]:
    seen: dict[str, object] = {}
    queue = [root]
    while queue:
        name = queue.pop()
        try:
            dist = distribution(name)
        except PackageNotFoundError:
            continue
        key = dist.metadata["Name"].lower()
        if key in seen:
            continue
        seen[key] = dist
        queue.extend(n for n in (requirement_name(r) for r in dist.requires or []) if n)
    seen.pop("polyglass", None)
    return seen


def main() -> None:
    rows = []
    for _, dist in sorted(collect("polyglass").items()):
        meta = dist.metadata
        rows.append(f"| {meta['Name']} | {meta['Version']} | {license_of(meta)} | {homepage(meta)} |")
    text = "\n".join(
        [
            "# Third-party notices",
            "",
            "Polyglass is licensed under the GNU GPL v3 or later (see LICENSE). It is built on the open-source",
            "libraries below, each under its own licence. Their full licence texts are included in the installed",
            "packages and in release builds.",
            "",
            "This file is generated by `tools/third_party_notices.py`; do not edit it by hand.",
            "",
            "| Package | Version | Licence | Homepage |",
            "|---|---|---|---|",
            *rows,
            "",
        ]
    )
    (ROOT / "THIRD_PARTY_NOTICES.md").write_text(text, encoding="utf-8")
    print(f"Wrote {len(rows)} packages to THIRD_PARTY_NOTICES.md")


if __name__ == "__main__":
    main()
